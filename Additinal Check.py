import numpy as np
from scipy import stats

# Данные
data_2019 = np.array([3.5, 3.9, 5.5, 5.9, 9.6, 20.2, 25.1, 27.2, 33.5, 25.8, 31.0, 31.4, 36.9, 34.8, 40.9, 41.5, 42.1, 39.4, 45.3, 40.6, 48.2, 59.6, 61.3, 69.1, 71.9, 70.3, 78.7, 99.3, 79.4, 127.9])
data_2021 = np.array([3.8, 3.9, 5.5, 5.4, 10.1, 15.8, 25.7, 27.0, 27.6, 29.0, 30.5, 30.5, 33.4, 34.0, 40.5, 42.3, 42.7, 43.5, 43.5, 44.3, 52.0, 57.7, 62.2, 67.5, 69.1, 69.9, 77.1, 100.2, 105.7, 126.0])

alpha = 0.05 # Уровень значимости

print("-" * 15 + " ДОПОЛНИТЕЛЬНЫЕ КРИТЕРИИ (РАЗДЕЛ 2.8) " + "-" * 15)

# --- 5. КРИТЕРИЙ РАНГОВОЙ КОРРЕЛЯЦИИ КЕНДАЛЛА ---
# Оценивает согласованность рангов и устойчив к выбросам
# H0: Статистически значимая связь между 2019 и 2021 гг. отсутствует
# H1: Существует значимая корреляционная связь (структура сохранена)

tau, p_k = stats.kendalltau(data_2019, data_2021)

print(f"\n--- 5. КРИТЕРИЙ КЕНДАЛЛА (Стабильность системы) ---")
print(f"Коэффициент Тау-Кендалла: {tau:.4f}")
print(f"p-value: {p_k:.4e}")
print(f"Результат: {'Связи нет' if p_k > alpha else 'Есть статистически значимая связь'}")
print("-" * 65)

# --- 6. КРИТЕРИЙ КРАСКЕЛЛА-УОЛЛИСА (Раздел 2.8) ---
# Разделим 30 стран 2021 года на 3 группы по 10 стран
group_low = data_2021[0:10]
group_mid = data_2021[10:20]
group_high = data_2021[20:30]

# H0: Медианы всех трех групп равны (различий между уровнями стран нет)
# H1: Есть значимые различия хотя бы между двумя группами

h_stat, p_h = stats.kruskal(group_low, group_mid, group_high)

print(f"\n--- 6. КРИТЕРИЙ КРАСКЕЛЛА-УОЛЛИСА (Сравнение 3-х уровней 2021) ---")
print(f"Статистика H: {h_stat:.4f}")
print(f"p-value: {p_h:.4e}")
print(f"Результат: {'Различий нет' if p_h > alpha else 'Обнаружены СТАТИСТИЧЕСКИ ЗНАЧИМЫЕ различия между группами'}")
print("-" * 75)
