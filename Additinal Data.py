import numpy as np
from scipy import stats

# Данные для анализа (2.9)
# Ресурсная база (койки)
beds_2021 = np.array([3.8, 3.9, 5.5, 5.4, 10.1, 15.8, 25.7, 27.0, 27.6, 29.0, 30.5, 30.5, 33.4, 34.0, 40.5, 42.3, 42.7, 43.5, 43.5, 44.3, 52.0, 57.7, 62.2, 67.5, 69.1, 69.9, 77.1, 100.2, 105.7, 126.0])
# Целевой показатель (продолжительность жизни)
life_exp = np.array([59.1, 70, 69, 73.1, 70.8, 79, 81.6, 76.4, 81.5, 81.6, 81.7, 82.2, 74.6, 82.9, 72.2, 79.6, 73.7, 72.9, 70.1, 73, 77.6, 81.9, 75.4, 74.4, 81, 70, 80.5, 73.1, 70.1, 84.5])

alpha = 0.05

print("-" * 15 + " ДОБАВЛЕНИЕ ДОПОЛНИТЕЛЬНЫХ ДАННЫХ (РАЗДЕЛ 2.9) " + "-" * 15)

# --- 1. КРИТЕРИЙ КЕНДАЛЛА ---
# H0: Статистически значимая связь между кол-вом коек и продолжительностью жизни отсутствует
# H1: Существует значимая корреляционная связь
tau, p_k = stats.kendalltau(beds_2021, life_exp)

print(f"\n--- КРИТЕРИЙ КЕНДАЛЛА (Стабильность системы) ---")
print(f"Коэффициент Тау-Кендалла: {tau:.4f}")
print(f"p-value: {p_k:.4f}")
print(f"Результат: {'Связи нет' if p_k > alpha else 'Есть статистически значимая связь'}")

# --- 2. КРИТЕРИЙ СПИРМЕНА ---
# H0: Монотонная зависимость между мощностью фонда и долголетием отсутствует
# H1: Существует значимая монотонная зависимость
rho, p_s = stats.spearmanr(beds_2021, life_exp)

print(f"\n--- КРИТЕРИЙ СПИРМЕНА (Теснота связи) ---")
print(f"Коэффициент Спирмена: {rho:.4f}")
print(f"p-value: {p_s:.4f}")
print(f"Результат: {'Связи нет' if p_s > alpha else 'Есть статистически значимая связь'}")

# --- 3. КРИТЕРИЙ МАННА-УИТНИ ---
# Разделяем страны на две группы: "Мало коек" (первые 15) и "Много коек" (последние 15)
group_low = life_exp[0:15]
group_high = life_exp[15:30]

# H0: Распределения продолжительности жизни в обеих группах идентичны
# H1: В группе с большим числом коек продолжительность жизни статистически выше
u_stat, p_u = stats.mannwhitneyu(group_low, group_high, alternative='two-sided')

print(f"\n--- КРИТЕРИЙ МАННА-УИТНИ (Сравнение групп стран) ---")
print(f"Статистика U: {u_stat:.4f}")
print(f"p-value: {p_u:.4f}")
print(f"Результат: {'Различий нет' if p_u > alpha else 'Обнаружены статистически значимые различия'}")
print("-" * 75)
