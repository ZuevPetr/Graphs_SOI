import numpy as np
from scipy import stats

data_2019 = np.array([3.8, 2.9, 6.5, 8.9, 9.6, 20.2, 25.1, 27.2, 33.5, 28.8, 31.0, 31.4, 36.9, 34.8, 40.9, 41.5, 42.1, 39.4, 45.3, 40.6, 48.2, 59.6, 61.3, 69.1, 71.9, 70.3, 78.7, 99.3, 79.4, 127.9])
data_2021 = np.array([3.6, 3.9, 6.6, 9.4, 10.1, 19.8, 25.7, 27.0, 27.6, 29.0, 30.5, 30.9, 33.4, 34.0, 40.5, 42.3, 42.7, 43.5, 43.9, 44.3, 52.0, 57.7, 62.2, 67.9, 69.1, 69.9, 77.1, 100.2, 105.7, 126.0])

alpha = 0.05 # Уровень значимости

print("--- 1. КРИТЕРИЙ ШАПИРО-УИЛКА (Проверка на нормальность) ---")
# Используется для обоснования выбора непараметрических тестов
# H0: Распределение нормальное
# H1: Распределение отлично от нормального
stat19, p19 = stats.shapiro(data_2019)
stat21, p21 = stats.shapiro(data_2021)
print(f"2019: p-value = {p19:.4f}. {'Нормальное' if p19 > alpha else 'НЕ нормальное'}")
print(f"2021: p-value = {p21:.4f}. {'Нормальное' if p21 > alpha else 'НЕ нормальное'}")
print("-" * 59)

print("\n--- 2. КРИТЕРИЙ ВИЛКОКСОНА (Связные выборки) ---")
# Сравниваем одни и те же страны в разные годы
# H0: Распределения идентичны (нет значимых изменений в количестве коек)
# H1: Существуют значимые различия (пандемия или время повлияли на данные)
stat_w, p_w = stats.wilcoxon(data_2019, data_2021)
print(f"Статистика Вилкоксона: {stat_w}")
print(f"p-value: {p_w:.4f}")
print(f"Результат: {'Гипотеза H0 принимается' if p_w > alpha else 'Гипотеза H0 отвергается (есть различия)'}")
print("-" * 50)

print("\n--- 3. КРИТЕРИЙ КОРРЕЛЯЦИИ СПИРМЕНА ---")
# Проверяем наличие зависимости между 2019 и 2021 годами
# H0: Ранговая корреляция равна 0 (зависимости нет)
# H1: Существует зависимость
rho, p_s = stats.spearmanr(data_2019, data_2021)
print(f"Коэффициент Спирмена: {rho:.4f}")
print(f"p-value: {p_s:.4f}")
print(f"Результат: {'Связи нет' if p_s > alpha else 'Есть статистически значимая связь'}")
print("-" * 50)

print("\n--- 4. КРИТЕРИЙ МАННА-УИТНИ (Сравнение двух групп за 2021 год) ---")
# Делим выборку на две группы: "низкие показатели" и "высокие показатели"
group_low = data_2021[:15]   # Первые 15 стран
group_high = data_2021[15:]  # Последние 15 стран

# H0: Распределения в группах идентичны (различий нет)
# H1: Существуют значимые различия между группами
stat_mw, p_mw = stats.mannwhitneyu(group_low, group_high)

print(f"Статистика Манна-Уитни: {stat_mw}")
print(f"p-value: {p_mw:.4e}") # Используем научный формат, так как p будет очень маленьким
print(f"Результат: {'Различия НЕ значимы' if p_mw > alpha else 'Различия СТАТИСТИЧЕСКИ ЗНАЧИМЫ'}")
print("-" * 65)
